    private void load() {
    DefaultTableModel model = (DefaultTableModel) tblmenu.getModel();
    model.setRowCount(0);

    tblmenu.setRowHeight(64);

    for (MenuItem m : menu.values()) {
        int id = m.getItemId();
        
        
        //for food items
        if(m instanceof FoodItem){
            FoodItem f =(FoodItem)m;
            
        model.addRow(new Object[] {
            id,
            
            "Food",
            f.getName(),
            f.getDescription(),
            f.getPrice(),
            f.getServingSize(),
            null
            
            
           // new ImageIcon("images/" + id + ".jpg")
        });
    }
        
        else if(m instanceof DrinkItem){
            DrinkItem d =(DrinkItem)m;
            
             model.addRow(new Object[] {
            id,
            
            "Drink",
            d.getName(),
            d.getDescription(),
            d.getPrice(),
            null,
            d.getVolume()
                     
            
           // new ImageIcon("images/" + id + ".jpg")
        });
            
        }
}



    }
    
