    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        
        if (tblmenu.isEditing()) {
            tblmenu.getCellEditor().stopCellEditing();
        }
        
         DefaultTableModel model = (DefaultTableModel) tblmenu.getModel();

    int row = tblmenu.getSelectedRow();

    if(row == -1){
        return;
    }

    int id = Integer.parseInt(model.getValueAt(row,0).toString());
    String type = model.getValueAt(row,1).toString();
    String name = model.getValueAt(row,2).toString();
    String desc = model.getValueAt(row,3).toString();
    double price = Double.parseDouble(model.getValueAt(row,4).toString());

    MenuItem item;

    if(type.equalsIgnoreCase("Food")){

        String serving = model.getValueAt(row,5).toString();

        item = new FoodItem(id,name,desc,price,serving);

    } else {

        String volume = model.getValueAt(row,6).toString();

        item = new DrinkItem(id,name,desc,price,volume);
    }

   mRepo.addItem(item);

mRepo.saveMenu();

    editingAllowed = false;
    addingMode = false;
    javax.swing.JOptionPane.showMessageDialog(this, "Menu saved");
    }//GEN-LAST:event_btnSaveActionPerformed

