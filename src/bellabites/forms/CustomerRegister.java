    private void ButtonSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ButtonSubmitActionPerformed
        // TODO add your handling code here:
        String fullName =TextfieldFullName.getText();
        String email =TextFieldEmail.getText();
        String pass=new String(TextFieldPassword.getPassword());
        
        String pass2=new String(TextFieldReEnter.getPassword());
        String address=TextFieldAddress.getText();
        String phoneNo=TextFieldPhoneNumber.getText();
        
       
        
        
        if(pass.equals(pass2)){
                        if(email.contains("@")&&email.contains(".")){
                            if(users.emailExists(email)==true){
                                JOptionPane.showMessageDialog(null, "account already exists with this email");}
                            else{

                                
                                
                            
                            
                            try{
                                Customer newCustomer=new Customer(fullName,email,pass,address,phoneNo);
                                bellabitesSystem.RegisterCustomer(newCustomer);
                                
                                
                                JOptionPane.showMessageDialog(null, " Thanks for registering");
                                Home home = new Home();
                                home.setVisible(true);
                                this.dispose();
                                
                                //redirect
                            }
                            catch(Exception e){
                                System.out.println("failed to create customer");
                            }
                        }
                        }
                    
                        else{
                            JOptionPane.showMessageDialog(null, "email is not properly formatted");
                        }
                        
                                }
                    
        else{
            JOptionPane.showMessageDialog(null, " passwords do not match");
            
            
        }
        

    }//GEN-LAST:event_ButtonSubmitActionPerformed

