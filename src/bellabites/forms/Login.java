    private void ButtonSubmitLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ButtonSubmitLoginActionPerformed
        // TODO add your handling code here:
        
       
        String email=TextFieldEmail.getText();
        String pass=new String(TextFieldPassword.getPassword());
       
        
       User user= bellabiteSystem.Login(email, pass);
        
        if(user==null){
           JOptionPane.showMessageDialog(null,"Email or Password is incorrect please try again");
           TextFieldEmail.setText("");
           TextFieldPassword.setText("");
        }else if(user instanceof Customer){
            Customer cust=(Customer)user;
            CustomerHome custHome= new CustomerHome(cust);
            custHome.setVisible(true);
            this.dispose();

            
        }else if(user instanceof Staff){
            Staff staff=(Staff)user;
            StaffHome staffHome= new StaffHome(staff);
            staffHome.setVisible(true);
            this.dispose();
        }
    
        
        
        
        
      
           
           
       
       
      
        

        
    }//GEN-LAST:event_ButtonSubmitLoginActionPerformed

