    private void loadBasket() {
    DefaultTableModel model = (DefaultTableModel) tblbasket.getModel();
    model.setRowCount(0);

    tblbasket.setRowHeight(64);

    for (OrderLine m : basket) {
        
        int id = m.getMenuitemId();
        
        
        model.addRow(new Object[] {
            id,
            
            m.getName(),
            m.getPrice(),
            m.getQauntity(),
            m.getLineTotal()
           
        
        
       
            
        });
}
    
    for(OrderLine i:cust.getBasket()){
              
             total+=i.getLineTotal();
             
            
        }
        String t=Double.toString(total);
        lbltotal.setText("total: £"+ t);
        
    }



    

