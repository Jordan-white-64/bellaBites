         public Order getLatestOrder(int custId){

    Order latest = null;
LinkedHashMap<Integer,Order> orders=oRepo.getOrders();

    for(Order o : orders.values()){
        
        if(o.getCustId()== custId){
            
            if(latest == null || o.getOrderId() > latest.getOrderId()){
                latest = o;
            }
        }
    }

    return latest;
}
            
        


